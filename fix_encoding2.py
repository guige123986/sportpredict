current_lang = None
fixes_applied = 0

for i in range(new_i18n_line_start, min(new_i18n_line_end, len(lines))):
    line = lines[i]
    
    # Check if this line starts a new language block
    for lang in new_i18n_fixes.keys():
        if re.match(r'\s+' + lang + r':\s*\{', line):
            current_lang = lang
            break
    
    if current_lang is None:
        continue
    
    # Check if this line ends the language block
    if line.strip() == '},':
        current_lang = None
        continue
    
