            if key_match:
                prefix = key_match.group(1)
                # Replace the value part
                # Find the value - everything after the key pattern until the comma at end of line
                # Handle both single and double quoted values
                rest = line[key_match.end():]
                
                # Match '...', or "...", at the end (possibly with trailing whitespace)
                value_match = re.match(r"('.*?'|\".*?\"),?\s*$", rest)
